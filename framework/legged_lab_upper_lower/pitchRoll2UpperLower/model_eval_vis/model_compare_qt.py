            self.relation_combo.currentTextChanged.connect(self.on_relation_changed)
            self.backend_combo = QtWidgets.QComboBox()
            self.backend_combo.currentTextChanged.connect(self.update_view)
            self.image_combo = QtWidgets.QComboBox()
            self.image_combo.addItems(list(IMAGE_TYPES))
            self.image_combo.currentTextChanged.connect(self.update_view)
            self.source_combo = QtWidgets.QComboBox()
            self.source_combo.addItems(["all", "policy", "suspended", "other"])
            self.source_combo.currentTextChanged.connect(self.update_table)

            control_row = QtWidgets.QHBoxLayout()
            control_row.addWidget(QtWidgets.QLabel("relation"))
            control_row.addWidget(self.relation_combo)
            control_row.addWidget(QtWidgets.QLabel("backend"))
            control_row.addWidget(self.backend_combo)
            control_row.addWidget(QtWidgets.QLabel("plot"))
            control_row.addWidget(self.image_combo)
            control_row.addWidget(QtWidgets.QLabel("table source"))
            control_row.addWidget(self.source_combo)
            control_row.addStretch(1)

            self.summary_table = QtWidgets.QTableWidget()
            self.summary_table.setColumnCount(7)
            self.summary_table.setHorizontalHeaderLabels(["backend", "source", "output", "count", "MAE", "RMSE", "MaxAbs"])
            self.summary_table.horizontalHeader().setStretchLastSection(False)
            self.summary_table.horizontalHeader().setSectionResizeMode(QtWidgets.QHeaderView.ResizeMode.Interactive)
            self.configure_result_table(self.summary_table)

            self.image_label = QtWidgets.QLabel()
            self.image_label.setAlignment(QtCore.Qt.AlignmentFlag.AlignCenter)
            self.image_label.setBackgroundRole(QtGui.QPalette.ColorRole.Base)
            self.image_label.setSizePolicy(QtWidgets.QSizePolicy.Policy.Expanding, QtWidgets.QSizePolicy.Policy.Expanding)
            self.image_label.setScaledContents(False)
            self.image_scroll = QtWidgets.QScrollArea()
            self.image_scroll.setMinimumWidth(420)
            self.image_scroll.setWidgetResizable(True)
            self.image_scroll.setWidget(self.image_label)
            self.image_scroll.viewport().installEventFilter(self)

