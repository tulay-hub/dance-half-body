"""Qt browser for CSV-based PR/UL ankle model evaluation results.

This displays the artifacts generated by eval_visualize_pr_ul_models.py:
summary.csv, report.html, scatter plots, error histograms, and time-series plots.

Run:
    python -B pitchRoll2UpperLower/model_eval_vis/model_compare_qt.py
"""

from __future__ import annotations

import argparse
import csv
import os
from pathlib import Path
import subprocess
import sys


ROOT = Path(__file__).resolve().parent
PITCHROLL_DIR = ROOT.parent
DEFAULT_EVAL_DIR = ROOT / "csv_eval_vis"
DEFAULT_ANKLE_EVAL_DIR = ROOT / "ankle_model_eval_vis"
DEFAULT_DATA = PITCHROLL_DIR / "t_p_v" / "data" / "test"
DEFAULT_GMR_PYTHON = Path(os.environ.get("LENS110_GMR_PYTHON", sys.executable))
EVAL_SCRIPT = ROOT / "eval_visualize_pr_ul_models.py"
ANKLE_EVAL_SCRIPT = ROOT / "eval_ankle_model_data.py"
RELATION_ORDER = [
    "pr_to_ul_state",
    "ul_to_pr_state",
    "pr_to_ul_torque",
    "ul_to_pr_torque",
    "pr_to_ul_full",
    "ul_to_pr_full",
]
IMAGE_TYPES = {
    "overall": "overall_mae_rmse.png",
    "scatter": "scatter_true_vs_pred.png",
    "error_hist": "error_hist.png",
    "timeseries": "timeseries.png",
}


def clean_env(extra: dict[str, str] | None = None) -> dict[str, str]:
    env = os.environ.copy()
    env.pop("PYTHONPATH", None)
    env.pop("PYTHONHOME", None)
    env.setdefault("PYTHONDONTWRITEBYTECODE", "1")
    if extra:
        env.update(extra)
    return env


def maybe_reexec() -> None:
    try:
        import PyQt6  # noqa: F401
    except Exception:
        if (
            os.environ.get("ANKLE_EVAL_BROWSER_REEXECED") != "1"
            and DEFAULT_GMR_PYTHON.exists()
            and Path(sys.executable) != DEFAULT_GMR_PYTHON
        ):
            env = clean_env({"ANKLE_EVAL_BROWSER_REEXECED": "1"})
            print(f"[INFO] missing PyQt6; relaunching with {DEFAULT_GMR_PYTHON}")
            os.execve(
                str(DEFAULT_GMR_PYTHON),
                [str(DEFAULT_GMR_PYTHON), "-B", str(Path(__file__).resolve()), *sys.argv[1:]],
                env,
            )
        raise


def read_summary(eval_dir: Path) -> list[dict[str, str]]:
    path = eval_dir / "summary.csv"
    if not path.exists():
        return []
    with path.open("r", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def format_number(value: str) -> str:
    try:
        return f"{float(value):.6g}"
    except Exception:
        return value


