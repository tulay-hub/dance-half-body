            path_row.addWidget(QtWidgets.QLabel("eval dir"))
            path_row.addWidget(self.eval_dir_edit, 1)
            path_row.addWidget(self.reload_button)
            path_row.addWidget(self.run_eval_button)
            path_row.addWidget(self.open_report_button)

